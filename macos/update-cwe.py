# Rewrites Sources/CvedexKit/CWEList.swift from MITRE's latest CWE list, without deprecated entries.
import io
import pathlib
import urllib.request
import xml.etree.ElementTree as ET
import zipfile

data = urllib.request.urlopen("https://cwe.mitre.org/data/xml/cwec_latest.xml.zip").read()
with zipfile.ZipFile(io.BytesIO(data)) as archive:
    root = ET.fromstring(archive.read(archive.namelist()[0]))
ns = {"c": root.tag.split("}")[0].strip("{")}
names = {
    int(w.get("ID")): w.get("Name")
    for w in root.iterfind(".//c:Weakness", ns)
    if w.get("Status") != "Deprecated"
}
lines = "\n".join(f"{k}\t{v}" for k, v in sorted(names.items()))
out = pathlib.Path(__file__).parent / "Sources/CvedexKit/CWEList.swift"
out.write_text(
    f"// Generated by macos/update-cwe.py from CWE {root.get('Version')}. Do not edit.\n\n"
    f'extension CWE {{\n    static let list = #"""\n{lines}\n"""#\n}}\n'
)
print(f"CWE {root.get('Version')}: {len(names)} weaknesses")
